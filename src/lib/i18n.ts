// Multi-language (i18n) Engine for WebOmok (English, Japanese, Chinese, Korean)
// Automatically detects language from user's IP country with manual override & persistence

export type Language = 'ko' | 'en' | 'ja' | 'zh';

export interface LanguageOption {
  code: Language;
  name: string;
  flag: string;
}

export const SUPPORTED_LANGUAGES: LanguageOption[] = [
  { code: 'ko', name: '한국어', flag: '🇰🇷' },
  { code: 'en', name: 'English', flag: '🇺🇸' },
  { code: 'ja', name: '日本語', flag: '🇯🇵' },
  { code: 'zh', name: '中文', flag: '🇨🇳' },
];

/**
 * Determine initial language from detected IP country code
 */
export function detectLanguageFromCountry(countryCode: string): Language {
  const upper = (countryCode || '').toUpperCase();
  if (upper === 'KR') return 'ko';
  if (upper === 'JP') return 'ja';
  if (['CN', 'TW', 'HK', 'MO', 'SG'].includes(upper)) return 'zh';
  return 'en'; // Global default for all other countries
}

const STORAGE_LANG_KEY = 'webomok_lang_v1';

export function getSavedLanguage(): Language | null {
  if (typeof window === 'undefined') return null;
  try {
    const saved = localStorage.getItem(STORAGE_LANG_KEY);
    if (saved && ['ko', 'en', 'ja', 'zh'].includes(saved)) {
      return saved as Language;
    }
  } catch {
    // localstorage error
  }
  return null;
}

export function saveLanguage(lang: Language): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(STORAGE_LANG_KEY, lang);
  } catch {
    // localstorage error
  }
}

